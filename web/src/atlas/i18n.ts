export type MessageKey = keyof typeof messages;
export type Translate = (key: MessageKey, variables?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  return (key, variables) => {
    const label = locale === 'zh-Hant' ? key : messages[key][locale === 'en-US' ? 1 : 0];
    return variables ? label.replace(/\{(\w+)\}/g, (match, variable) => String(variables[variable] ?? match)) : label;
  };
}

export function getLocale(): Locale {
  const saved = localStorage.getItem('trace_atlas_locale');
  return saved && Object.prototype.hasOwnProperty.call(locales, saved) ? saved as Locale : 'zh-Hans';
}
